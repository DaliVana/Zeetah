//! Build helper: wrap the compiled `zeetah.wasm` (an anonymous import, see
//! build.zig) as a classic script that sets `ZEETAH_WASM_B64`. Pages opened
//! from `file://` can neither `fetch` a sibling `.wasm` nor load ES modules,
//! so the inline copy lets `web/index.html` work without a server; over
//! HTTP the loader still prefers the plain `.wasm` (streaming compile).
//!
//! Usage: embed <out.js>

const std = @import("std");

const wasm = @embedFile("zeetah_wasm");

pub fn main(init: std.process.Init) !void {
    const args = try init.minimal.args.toSlice(init.arena.allocator());
    if (args.len != 2) return error.Usage;

    const enc = std.base64.standard.Encoder;
    const head = "// Generated by `zig build` (src/embed.zig) - do not edit.\nvar ZEETAH_WASM_B64 = \"";
    const tail = "\";\n";
    const buf = try init.arena.allocator().alloc(u8, head.len + enc.calcSize(wasm.len) + tail.len);
    @memcpy(buf[0..head.len], head);
    _ = enc.encode(buf[head.len..][0..enc.calcSize(wasm.len)], wasm);
    @memcpy(buf[buf.len - tail.len ..], tail);

    try std.Io.Dir.cwd().writeFile(init.io, .{ .sub_path = args[1], .data = buf });
}
